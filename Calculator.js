// For Subtraction 
const subtractMethod = () => {
  function subtractedMethod(number1, number2) {
    return number1 - number2;
  }
  const result = subtractedMethod(5, 4);
  console.log(result); 
}
// Call the subtraction method so the code runs
subtractMethod();
// End of Subtraction 


